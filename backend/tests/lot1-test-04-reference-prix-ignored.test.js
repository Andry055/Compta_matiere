'use strict';

/**
 * Lot 1 Test 4: Reference and prix ignored from client
 * Une référence ou une valeur_unitaire envoyée par le client est ignorée : la référence est générée et le montant vient de la fiche.
 */

const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const racine = path.join(__dirname, '..');
const SORTIE_CONTROLEUR = path.join(racine, 'src', 'api', 'sortie', 'controllers', 'sortie.js');

test('Lot 1.4 - Reference ignored: body.reference is ignored', async () => {
  const controleurSource = fs.readFileSync(SORTIE_CONTROLEUR, 'utf8');

  // Check that body.reference is ignored (reference is always generated by server)
  assert.match(controleurSource, /Ignorer toujours body\.reference : la référence est toujours générée par le serveur/);
  assert.match(controleurSource, /let reference = '';/);
});

test('Lot 1.4 - Reference generated with collision handling', async () => {
  const controleurSource = fs.readFileSync(SORTIE_CONTROLEUR, 'utf8');

  // Check that reference generation handles collisions
  assert.match(controleurSource, /Essayer jusqu'à 3 fois en cas de violation d'unicité/);
  assert.match(controleurSource, /for \(let tentative = 0; tentative < 3; tentative\+\+\)/);
  assert.match(controleurSource, /Vérifier si cette référence est déjà utilisée/);
});

test('Lot 1.4 - Prix ignored: client valeur_unitaire is ignored', async () => {
  const controleurSource = fs.readFileSync(SORTIE_CONTROLEUR, 'utf8');

  // Check that client valeur_unitaire is ignored
  assert.match(controleurSource, /Ignorer valeur_unitaire envoyée par le client, prendre celle de la fiche matériel/);
});

test('Lot 1.4 - Prix taken from material file', async () => {
  const controleurSource = fs.readFileSync(SORTIE_CONTROLEUR, 'utf8');

  // Check that valeur unitaire is taken from material
  assert.match(controleurSource, /const valeurUnitaire = Number\(materiel\.valeur_unitaire\) \|\| 0;/);
});

test('Lot 1.4 - Montant field added and calculated', async () => {
  const controleurSource = fs.readFileSync(SORTIE_CONTROLEUR, 'utf8');

  // Check that montant field is added and calculated
  assert.match(controleurSource, /const montant = Number\(ligne\.quantite\) \* valeurUnitaire;/);
  assert.match(controleurSource, /montant: montant, \/\/ Champ ajouté, calculé par le serveur/);
});

test('Lot 1.4 - Validation: valeur unitaire must be > 0', async () => {
  const controleurSource = fs.readFileSync(SORTIE_CONTROLEUR, 'utf8');

  // Check that validation for valeur unitaire > 0 exists
  assert.match(controleurSource, /Refuser la ligne si valeur_unitaire est absente ou ≤ 0/);
  assert.match(controleurSource, /if \(!valeurUnitaire \|\| valeurUnitaire <= 0\)[\s\S]*?return badRequest\(/);
});